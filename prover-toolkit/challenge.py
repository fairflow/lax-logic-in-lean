#!/usr/bin/env python3
"""Build a challenge set that is not a walkthrough ending at the answer.

The first challenge set was generated by bare prefix truncation, which has a
property no instruction-not-to-peek can remove: *everything the ground-truth
proof used is, by construction, above the cut*.  Measured on those four files,
one had its answer in a sibling challenge file and two more had every
ingredient in the prefix; only one needed anything its own file did not
contain.  See `docs/toolkit-test-design.md`.

This adds the acceptance filters of that proposal (§4, "cheaper variant") on
top of `extract.py`, and emits blinded files:

  EXTERNAL CITATION   the ground-truth proof must cite at least one global
                      name that is NOT declared in the prefix, so the proof
                      genuinely needs something the challenge file lacks.
  NO VISIBLE TWIN     reject a target whose proof is near-identical to a
                      sibling's already visible in the prefix.  This is the
                      `conservativity` / `conservativity_prop` trap: the
                      second was proved 60 lines above the first.
  COMPILES            the emitted file must elaborate with exactly one
                      `sorry` and no errors.
  BLIND               the header names the group and nothing else: no line
                      count, no source file, no source line.

Usage:
    python3 challenge.py report                 # what the filters say, no output files
    python3 challenge.py build -o <dir> [-n N]  # emit and validate a set
"""

