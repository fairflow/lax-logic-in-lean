# ---------------------------------------------------------------- identifiers

# A global reference: dotted (`List.mem_cons_self`, `PLLND.erase`) or a bare
# name.  The negative lookbehind rejects Lean's anonymous-constructor dot
# (`.iden`, `.impIntro`), which resolves against the expected type's namespace
# and is therefore never evidence of an outside dependency.
IDENT_RE = re.compile(r"(?<![.\w'])([A-Za-z_][A-Za-z0-9_']*(?:\.[A-Za-z_][A-Za-z0-9_']*)*)")

DECL_NAME_RE = re.compile(
    r"^(?:@\[[^\]]*\]\s*)?"
    r"(?:private\s+|protected\s+|noncomputable\s+|partial\s+|unsafe\s+|scoped\s+)*"
    r"(?:theorem|lemma|def|abbrev|instance|structure|inductive|class|opaque|axiom)\s+"
    r"([A-Za-z_][A-Za-z0-9_'!?]*)",
    re.M,
)

# Tactics, keywords and term-level syntax.  A citation of one of these says
# nothing about what the proof depends on.
NOISE = frozenset("""
by exact refine apply intro intros rintro rcases obtain cases casesm induction
match with fun let have show from at in do then else if this simp simpa dsimp
omega decide native_decide rfl trivial constructor exists use left right
first try repeat all_goals any_goals focus rotate_left skip sorry admit
assumption contradiction absurd exfalso subst substs rw rewrite erw conv
unfold delta change calc gcongr positivity linarith nlinarith ring ring_nf
field_simp norm_num push_neg by_cases by_contra specialize revert clear
rename_i next case set generalize injection ext funext congr aesop tauto
convert cc solve_by_elim assumption' split splits stop guard_hyp guard_target
where deriving open section end namespace variable universe attribute
Type Prop Sort True False And Or Not Iff Eq Exists forall fun
nil cons some none inl inr mk fst snd val property
""".split())


def strip_comments(text: str) -> str:
    return extract.strip_comments_for_scan(text)


def declared_names(source: str) -> set[str]:
    """Every name declared at top level in `source`, plus its last component."""
    out: set[str] = set()
    for m in DECL_NAME_RE.finditer(source):
        n = m.group(1)
        out.add(n)
        out.add(n.rsplit(".", 1)[-1])
    # `inductive`/`structure` constructor names, one per indented `| Name`
    for m in re.finditer(r"^\s*\|\s*([A-Za-z_][A-Za-z0-9_']*)", source, re.M):
        out.add(m.group(1))
    return out


def cited(proof: str) -> set[str]:
    """Global names a proof appears to reference."""
    scan = strip_comments(proof)
    out = set()
    for m in IDENT_RE.finditer(scan):
        tok = m.group(1)
        if tok in NOISE:
            continue
        if "." not in tok and len(tok) <= 2:
            continue                      # h, ih, p — binders, not citations
        out.add(tok)
    return out


# Namespace roots from Lean core / Mathlib that the corpus index does not cover.
STDLIB_ROOTS = frozenset("""
List Nat Int Option Prod Sum Sigma Subtype Finset Set Multiset Array String
Bool Char Function Classical Decidable Quot Quotient And Or Iff Not Exists Eq
Ne Membership Std Lean Fin Vector Sublist Perm
""".split())


def is_global(tok: str, prefix_names: set[str], index_names: set[str]) -> bool:
    """Does `tok` reference a declaration, rather than project off a binder?

    `C.Ri`, `hw.elim` and `d.toSC` are dotted but are field access on local
    hypotheses, not dependencies on anything importable.  A dotted token only
    counts when its HEAD is a namespace we can actually name.
    """
    if "." in tok:
        head = tok.split(".", 1)[0]
        return (head in STDLIB_ROOTS or head in prefix_names
                or head in index_names)
    return tok in prefix_names or tok in index_names


def external_citations(item, prefix_names: set[str], index_names: set[str]) -> set[str]:
    """Globals the target needs that are NOT declared in the prefix.

    Both the proof AND the statement count.  The statement matters because a
    definitional dependency need never be named in the proof: `pfree_trans`
    cites nothing external, yet cannot be proved without knowing what
    `LJF.PFreeP` and `LJF.PFreeN` unfold to, and those live in another file.
    It was the one target of the original four that genuinely tested
    retrieval, and a proof-only filter drops it — which is how this was
    found.
    """
    self_names = {item.name, item.name.rsplit(".", 1)[-1]}
    out = set()
    for tok in cited(item.ground_truth) | cited(item.statement):
        if not is_global(tok, prefix_names, index_names):
            continue
        head = tok.rsplit(".", 1)[-1]
        if tok in self_names or head in self_names:
            continue                       # the target naming itself
        if tok in prefix_names or head in prefix_names:
            continue
        out.add(tok)
    return out


def proof_external(item, prefix_names: set[str], index_names: set[str]) -> set[str]:
    """External citations made by the PROOF — the strongest form of the signal.

    A statement-only dependency (`pfree_trans`) is real but weaker: you must
    know what the name unfolds to, yet the proof never writes it.  Targets are
    ranked on this count first, so a set built with `-n` takes the ones whose
    proofs reach outside before the ones whose statements merely mention it.
    """
    return {t for t in external_citations(item, prefix_names, index_names)
            if t in cited(item.ground_truth)}


# ------------------------------------------------------------ visible twins

def proof_shape(proof: str) -> list[str]:
    """Token bag of a proof, comments and binder noise removed."""
    scan = strip_comments(proof)
    return [t for t in IDENT_RE.findall(scan)
            if t not in NOISE and not ("." not in t and len(t) <= 2)]


MIN_SHAPE = 5


def overlap(a: list[str], b: list[str]) -> float:
    """Containment of the smaller token-set in the larger. 1.0 = identical set.

    Below `MIN_SHAPE` distinct tokens containment is degenerate — `by omega`
    is a subset of almost everything — so short proofs fall back to Jaccard,
    which does not reward being small.
    """
    sa, sb = set(a), set(b)
    if not sa or not sb:
        return 0.0
    if min(len(sa), len(sb)) < MIN_SHAPE:
        return len(sa & sb) / len(sa | sb)
    return len(sa & sb) / min(len(sa), len(sb))


def visible_twin(item, siblings: list, threshold: float) -> tuple[str | None, float]:
    """The most similar proof already visible in this item's prefix."""
    shape = proof_shape(item.ground_truth)
    best, score = None, 0.0
    for sib in siblings:
        if sib.name == item.name or sib.file != item.file:
            continue
        if sib.line >= item.line:          # not visible: it comes after the cut
            continue
        s = overlap(shape, proof_shape(sib.ground_truth))
        if s > score:
            best, score = sib.name, s
    return (best if score >= threshold else None), score


# ------------------------------------------------------------------- emission

BLIND_HEADER = """/- Challenge: `{name}`.  Group: {group}.
   Replace the `sorry`.  Do not look for the original proof.

   Deliberately not stated here: where this comes from, how long the known
   proof is, or how hard it is.  Those were hints. -/
"""


def render(item) -> str:
    return BLIND_HEADER.format(name=item.name, group=item.group) + \
        item.prefix.rstrip("\n") + "\n\n" + item.statement + " := by\n  sorry\n"


def compiles_with_one_sorry(text: str, repo: Path) -> tuple[bool, str]:
    """Elaborate `text`; require zero errors and exactly one sorry warning."""
    with tempfile.NamedTemporaryFile("w", suffix=".lean", dir=repo,
                                     delete=False, encoding="utf-8") as fh:
        fh.write(text)
        tmp = Path(fh.name)
    try:
        r = subprocess.run(["lake", "env", "lean", str(tmp)], cwd=repo,
                           capture_output=True, text=True, timeout=900)
        out = (r.stdout or "") + (r.stderr or "")
        errors = [l for l in out.splitlines() if ": error:" in l]
        # Lean spells this with BACKTICKS -- "declaration uses `sorry`".  An
        # earlier version matched straight quotes and so counted zero on every
        # file, rejecting the whole set.  Match the quoting loosely.
        sorries = [l for l in out.splitlines()
                   if re.search(r"declaration uses .?sorry", l)]
        if errors:
            return False, f"{len(errors)} error(s): {errors[0][:160]}"
        if len(sorries) != 1:
            return False, f"expected 1 sorry warning, got {len(sorries)}"
        return True, "ok"
    except subprocess.TimeoutExpired:
        return False, "timeout"
    finally:
        tmp.unlink(missing_ok=True)


